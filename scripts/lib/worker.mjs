/**
 * NAS worker: inbox job → draft branch → PR on GitHub or Gitea (POK-637).
 *
 * The worker owns a dedicated clone (`repoDir`) of the review repo (`repoUrl`,
 * where draft branches and PRs go). With `upstreamUrl` set, code changes from
 * the upstream main are brought into the review repo's main before each job
 * (fast-forward, or a merge when both sides moved; never a force push). Each
 * job then runs the repo's own CLI at the review main, so jobs always use the
 * latest merged pipeline code.
 */

import { spawn } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { parseJobFile, newCommandArgs } from "./inbox.mjs";

/** A file must be untouched this long before we pick it up (SMB copies land in pieces). */
const SETTLE_MS = 5000;

export const INBOX_DIRS = ["processing", "done", "failed"];
export const FORGES = ["github", "gitea"];

/** owner/repo from any http(s) or scp-style git URL: …/owner/repo(.git) */
export function parseRepoPath(repoUrl) {
  const m = repoUrl.match(/[/:]([^/:]+)\/([^/]+?)(?:\.git)?\/?$/);
  return m ? { owner: m[1], repo: m[2] } : null;
}

/** Default REST API base for a forge, derived from the repo URL. */
export function defaultForgeApi(forge, repoUrl) {
  if (forge === "github") return "https://api.github.com";
  const origin = /^https?:\/\//.test(repoUrl) ? new URL(repoUrl).origin : null;
  return origin ? `${origin}/api/v1` : null;
}

export function redact(text, secrets) {
  let out = String(text);
  for (const s of secrets.filter(Boolean)) out = out.split(s).join("***");
  return out;
}

/** Async so the worker stays responsive (signals, timers) during long pipeline runs. */
function defaultRun(cmd, args, { cwd, env } = {}) {
  return new Promise((resolve) => {
    const child = spawn(cmd, args, { cwd, env: { ...process.env, ...env } });
    let stdout = "";
    let stderr = "";
    child.stdout.on("data", (d) => (stdout += d));
    child.stderr.on("data", (d) => (stderr += d));
    child.on("error", (error) => resolve({ status: 1, stdout, stderr: stderr || error.message }));
    child.on("close", (code) => resolve({ status: code ?? 1, stdout, stderr }));
  });
}

/**
 * Markdown PR body summarizing the pipeline run.
 */
export function buildPrBody({ job, jobFile, slug, title, runResult }) {
  const rows = (runResult?.results ?? []).map((r) => {
    const outcome = r.error ? "❌ error" : r.blocked ? "⏸ blocked" : r.handoff ? "➡ handoff" : "✅ written";
    return `| \`${r.step}\` | ${r.provider} | ${outcome} |`;
  });
  const problems = (runResult?.results ?? [])
    .filter((r) => r.error || r.blocked)
    .map((r) => `- **${r.step}:** ${(r.error ?? r.reason).split("\n").join("\n  ")}`);

  return `Generated by the Draftsmith NAS worker from \`inbox/${jobFile}\`.

- **Source:** ${job.url}
- **Slug:** \`${slug}\`
- **Title:** ${title}
- **Channels:** ${job.channels.join(", ")}${job.angle ? `\n- **Angle:** ${job.angle}` : ""}

## Pipeline

| Step | Provider | Result |
|------|----------|--------|
${rows.join("\n")}
${problems.length ? `\n## Needs attention\n\n${problems.join("\n")}\n` : ""}
## Review before publishing

- [ ] Commands, APIs, and versions are correct (local model; verify everything)
- [ ] Voice matches \`style/iostom-style-guide.md\`
- [ ] Screenshots captured for each \`<!-- image: … -->\`
- [ ] Follow \`docs/publish-checklist.md\`
`;
}

/**
 * @param {object} opts
 * @param {string} opts.inboxDir
 * @param {string} opts.repoDir        worker-owned clone (created on first job)
 * @param {string} opts.repoUrl        review repo: draft branches are pushed and PRs opened here
 * @param {string} [opts.upstreamUrl]  code source whose main is synced into the review main
 * @param {"github"|"gitea"} [opts.forge]
 * @param {string} [opts.forgeApi]     REST API base (default derived from forge + repoUrl)
 * @param {string} [opts.forgeToken]
 * @param {string} [opts.forgeUser]    basic-auth user for git over http (gitea: token owner)
 * @param {{owner: string, repo: string}} [opts.forgeRepo]  default: parsed from repoUrl
 * @param {string} [opts.ingestGithubToken]  optional GitHub token for ingest rate limits
 * @param {string} opts.ollamaHost
 * @param {boolean} [opts.dryRun]      commit locally only; no push / PR
 */
export function createWorker({
  inboxDir,
  repoDir,
  repoUrl,
  upstreamUrl = null,
  forge = "github",
  forgeApi = null,
  forgeToken = null,
  forgeUser = null,
  forgeRepo = null,
  ingestGithubToken = null,
  ollamaHost,
  dryRun = false,
  baseBranch = "main",
  gitUser = { name: "Draftsmith Worker", email: "draftsmith-worker@users.noreply.github.com" },
  log = (msg) => console.log(`[${new Date().toISOString()}] ${msg}`),
  run = defaultRun,
  fetchImpl = fetch,
  now = () => new Date(),
}) {
  if (!FORGES.includes(forge)) throw new Error(`forge: must be one of ${FORGES.join(", ")}`);
  const repoPath = forgeRepo ?? parseRepoPath(repoUrl);
  const api = forgeApi ?? defaultForgeApi(forge, repoUrl);
  const secrets = [forgeToken, ingestGithubToken];
  const say = (msg) => log(redact(msg, secrets));
  const identity = ["-c", `user.name=${gitUser.name}`, "-c", `user.email=${gitUser.email}`];
  let ollamaWasUp = null;

  for (const dir of INBOX_DIRS) mkdirSync(join(inboxDir, dir), { recursive: true });

  // Token travels as a per-command header scoped to the review repo's host; never in .git/config.
  const authArgs = () => {
    if (!forgeToken || !/^https?:\/\//.test(repoUrl)) return [];
    const user = forge === "github" ? "x-access-token" : forgeUser ?? repoPath?.owner ?? "git";
    const basic = Buffer.from(`${user}:${forgeToken}`).toString("base64");
    return ["-c", `http.${new URL(repoUrl).origin}/.extraheader=AUTHORIZATION: basic ${basic}`];
  };

  async function git(args, { auth = false, allowFail = false } = {}) {
    const cwd = existsSync(join(repoDir, ".git")) ? repoDir : undefined;
    const r = await run("git", [...(auth ? authArgs() : []), ...args], { cwd });
    if (r.status !== 0 && !allowFail) {
      throw new Error(`git ${args[0]} failed: ${redact((r.stderr || r.stdout).trim(), secrets)}`);
    }
    return r;
  }

  const hasRef = async (ref) => (await git(["rev-parse", "--verify", "--quiet", ref], { allowFail: true })).status === 0;
  const isAncestor = async (a, b) => (await git(["merge-base", "--is-ancestor", a, b], { allowFail: true })).status === 0;

  /**
   * Bring upstream main into the review repo's main. Never force-pushes:
   * fast-forward when possible, merge when both sides moved, fail on conflict.
   */
  async function syncUpstream() {
    const remotes = (await git(["remote"])).stdout.split("\n");
    if (!remotes.includes("upstream")) await git(["remote", "add", "upstream", upstreamUrl]);
    await git(["fetch", "--quiet", "upstream", baseBranch]);

    const up = `upstream/${baseBranch}`;
    const mine = `origin/${baseBranch}`;
    let target = null;

    if (!(await hasRef(mine))) {
      target = up; // empty review repo: seed it
      say(`review repo has no ${baseBranch}; seeding from upstream`);
    } else if (await isAncestor(up, mine)) {
      return; // up to date, or review main is ahead with approved drafts
    } else if (await isAncestor(mine, up)) {
      target = up;
      say(`fast-forwarding review ${baseBranch} to upstream`);
    } else {
      await git(["checkout", "--quiet", "--force", "--detach", mine]);
      const merged = await git([...identity, "merge", "--no-edit", "-m", `Merge upstream ${baseBranch} into review ${baseBranch}`, up], {
        allowFail: true,
      });
      if (merged.status !== 0) {
        await git(["merge", "--abort"], { allowFail: true });
        throw new Error(`upstream ${baseBranch} conflicts with review ${baseBranch}; resolve by hand in ${repoDir}`);
      }
      target = "HEAD";
      say(`merged upstream ${baseBranch} into review ${baseBranch}`);
    }

    if (dryRun) {
      say(`dry run: not pushing review ${baseBranch}; basing this job on the synced commit`);
      return target;
    }
    await git(["push", "--quiet", "origin", `${target}:refs/heads/${baseBranch}`], { auth: true });
    await git(["fetch", "--quiet", "origin"], { auth: true });
    return null;
  }

  async function prepareRepo() {
    if (!existsSync(join(repoDir, ".git"))) {
      mkdirSync(repoDir, { recursive: true });
      await git(["clone", "--quiet", repoUrl, repoDir], { auth: true });
    } else {
      await git(["fetch", "--quiet", "--prune", "origin"], { auth: true });
    }

    let base = `origin/${baseBranch}`;
    if (upstreamUrl) {
      const unpushed = await syncUpstream();
      if (unpushed) base = (await git(["rev-parse", unpushed])).stdout.trim();
    }

    await git(["checkout", "--quiet", "--force", "--detach", base]);
    await git(["reset", "--quiet", "--hard", base]);
    await git(["clean", "-fdq"]);
  }

  async function uniqueBranch(slug) {
    const base = `draft/${slug}`;
    const taken = (await git(["ls-remote", "--heads", "origin", base], { auth: true })).stdout.trim();
    if (!taken) return base;
    const stamp = now().toISOString().slice(0, 16).replace(/[-:T]/g, "");
    return `${base}-${stamp}`;
  }

  async function ollamaReachable() {
    try {
      const res = await fetchImpl(new URL("/api/version", ollamaHost), { signal: AbortSignal.timeout(10000) });
      return res.ok;
    } catch {
      return false;
    }
  }

  async function openPullRequest({ branch, title, body, draft }) {
    if (!repoPath) throw new Error(`cannot open PR: cannot parse owner/repo from ${repoUrl}`);
    if (!api) throw new Error(`cannot open PR: no API base for ${forge} (set FORGE_API)`);
    if (!forgeToken) throw new Error("cannot open PR: FORGE_TOKEN is not set");

    const url = `${api}/repos/${repoPath.owner}/${repoPath.repo}/pulls`;
    const request =
      forge === "github"
        ? {
            headers: {
              authorization: `Bearer ${forgeToken}`,
              accept: "application/vnd.github+json",
              "x-github-api-version": "2022-11-28",
            },
            payload: { title, head: branch, base: baseBranch, body, draft },
          }
        : {
            // Gitea marks work-in-progress PRs with a title prefix instead of a draft flag.
            headers: { authorization: `token ${forgeToken}`, accept: "application/json" },
            payload: { title: draft ? `WIP: ${title}` : title, head: branch, base: baseBranch, body },
          };

    const res = await fetchImpl(url, {
      method: "POST",
      headers: { ...request.headers, "content-type": "application/json" },
      body: JSON.stringify(request.payload),
    });
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new Error(`${forge} PR create failed: HTTP ${res.status} ${data.message ?? ""}`.trim());
    return data.html_url;
  }

  function finish(claimedPath, folder, logText) {
    const name = basename(claimedPath);
    renameSync(claimedPath, join(inboxDir, folder, name));
    writeFileSync(join(inboxDir, folder, `${name}.log`), `${redact(logText, secrets)}\n`, "utf8");
  }

  /**
   * Process one claimed job file. Never throws; returns { ok, prUrl?, error? }.
   */
  async function processJob(claimedPath) {
    const jobFile = basename(claimedPath);
    const lines = [`job: ${jobFile}`, `started: ${now().toISOString()}`];
    const note = (msg) => {
      lines.push(msg);
      say(`${jobFile}: ${msg}`);
    };

    try {
      const job = parseJobFile(readFileSync(claimedPath, "utf8"));
      note(`url: ${job.url} → slug ${job.slug}`);

      await prepareRepo();
      if (existsSync(join(repoDir, "articles", "drafts", job.slug))) {
        throw new Error(`slug "${job.slug}" already exists on ${baseBranch}; add a "slug:" line with a new slug`);
      }

      const branch = await uniqueBranch(job.slug);
      await git(["checkout", "--quiet", "-B", branch]);

      const ghToken = forge === "github" ? forgeToken : ingestGithubToken;
      const nodeEnv = { GITHUB_TOKEN: ghToken ?? "", OLLAMA_HOST: ollamaHost };
      const created = await run(process.execPath, ["scripts/draftsmith.mjs", ...newCommandArgs(job)], { cwd: repoDir, env: nodeEnv });
      if (created.status !== 0) {
        throw new Error(`draftsmith new failed: ${(created.stderr || created.stdout).trim()}`);
      }
      const scaffold = JSON.parse(created.stdout);
      note(`ingested (${scaffold.link_type}): ${scaffold.title}`);

      const ran = await run(process.execPath, ["scripts/draftsmith.mjs", "run", job.slug, "--provider", "ollama", "--json"], {
        cwd: repoDir,
        env: nodeEnv,
      });
      let runResult;
      try {
        runResult = JSON.parse(ran.stdout);
      } catch {
        throw new Error(`draftsmith run failed: ${(ran.stderr || ran.stdout).trim()}`);
      }
      const stepErrors = runResult.results.filter((r) => r.error);
      for (const r of runResult.results) {
        note(`step ${r.step}: ${r.error ? `ERROR ${r.error.split("\n")[0]}` : r.blocked ? `blocked (${r.reason})` : "ok"}`);
      }

      await git(["add", "-A", "articles/drafts", "export"]);
      const title = scaffold.title;
      await git([
        ...identity,
        "commit", "--quiet",
        "-m", `Draft: ${title} (${job.slug})`,
        "-m", `Source: ${job.url}\nGenerated by the Draftsmith NAS worker from inbox/${jobFile}.`,
      ]);

      if (dryRun) {
        note(`dry run: committed on local branch ${branch} in ${repoDir}; not pushed`);
        finish(claimedPath, "done", lines.join("\n"));
        return { ok: true, branch, dryRun: true };
      }

      await git(["push", "--quiet", "origin", `HEAD:refs/heads/${branch}`], { auth: true });
      const prUrl = await openPullRequest({
        branch,
        title: `Draft: ${title}`,
        body: buildPrBody({ job, jobFile, slug: job.slug, title, runResult }),
        draft: stepErrors.length > 0,
      });
      note(`PR: ${prUrl}${stepErrors.length ? " (draft — a step failed, see PR body)" : ""}`);
      finish(claimedPath, "done", lines.join("\n"));
      return { ok: true, branch, prUrl };
    } catch (error) {
      note(`FAILED: ${error.message}`);
      finish(claimedPath, "failed", lines.join("\n"));
      return { ok: false, error: redact(error.message, secrets) };
    }
  }

  /** Oldest settled job file in the inbox root, or null. */
  function nextJob() {
    const cutoff = now().getTime() - SETTLE_MS;
    const files = readdirSync(inboxDir, { withFileTypes: true })
      .filter((d) => d.isFile() && !d.name.startsWith(".") && !d.name.startsWith("@") && !d.name.endsWith(".log"))
      .map((d) => ({ name: d.name, mtime: statSync(join(inboxDir, d.name)).mtimeMs }))
      .filter((f) => f.mtime <= cutoff)
      .sort((a, b) => a.mtime - b.mtime);
    return files[0]?.name ?? null;
  }

  /**
   * One poll: pick the next job if Ollama is reachable. Returns the job
   * result, or null when idle/waiting.
   */
  async function pollOnce() {
    const name = nextJob();
    if (!name) return null;

    const up = await ollamaReachable();
    if (up !== ollamaWasUp) {
      say(up ? `Ollama reachable at ${ollamaHost}` : `Ollama not reachable at ${ollamaHost}; jobs wait in the inbox`);
      ollamaWasUp = up;
    }
    if (!up) return null;

    const claimed = join(inboxDir, "processing", name);
    renameSync(join(inboxDir, name), claimed);
    return processJob(claimed);
  }

  /** Re-queue jobs left in processing/ by a crash or restart. */
  function recover() {
    for (const name of readdirSync(join(inboxDir, "processing"))) {
      renameSync(join(inboxDir, "processing", name), join(inboxDir, name));
      say(`re-queued ${name} from processing/`);
    }
  }

  return { pollOnce, processJob, recover, prepareRepo };
}
